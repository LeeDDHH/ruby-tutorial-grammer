=begin
クラス、インスタンス
設計図→クラス
実際のもの→インスタンス

クラス＝プログラムの設計図
設計図にはこんな機能があると書いてある
設計図の名前は必ず大文字で書く

インスタンス＝設計図から作られた実際のもの
設計図からnewで作れる
同じ設計図から何個でも作れる
それぞれ別のモノとして扱える

それぞれのインスタンスは独立した存在

Rubyにおけるオブジェクト
Rubyでは文字列や数値なども含めて、すべてがオブジェクトとして扱われている
オブジェクトとは、あるクラスから作られたインスタンスのこと
=end

class Dog
  def bark
    puts "ワンワン"
  end
end

dog = Dog.new
dog.bark

shoro = Dog.new
shoro.bark
